"""OCRia-1's layout boxes on one port: the model card's experimental `ocria_grounding` package, run as its
examples/serve_boxes.py runs it (the default "accurate-layout" method, with Docling's Heron detector), for
answers generated by the vLLM server beside it (start.sh).

    POST /ground  {"image_png_b64", "answer", "pdf_b64" | null, "dpi", "render_size": [w, h] | null}
                  (or the card's "words" in place of the last three)
      -> {"width", "height", "items": [{"type", "label", "md", "box": [x0, y0, x1, y1], "start"}], "served"}
    GET  /served  -> {"weights", "revision", "detector", "detector_revision", "transformers"}

`image_png_b64` is the exact page image the answer was generated from and `answer` the raw answer, as the
card asks. For a PDF page, `pdf_b64` is the one-page PDF: its text-layer words are read with
`ocria_grounding.pdf.page_words` at `dpi` (the frame of a render at `dpi`, `render_size` pixels) and scaled
to the image's pixels, as `render_pdf_page` gives them for a page the model saw at that size. With no PDF,
the words come from the model's attention. One request at a time runs on the GPU; run several servers, one
port each, for throughput.

The weights and the package come from the model repository at REVISION and the detector from its own
repository at DETECTOR_REVISION; none of their code is in this repository. OCRia-1 and `ocria_grounding` are
under the OCRia-1 Model and Code License (LlamaIndex, Inc.); Heron is Apache-2.0.
"""
from __future__ import annotations

import argparse
import base64
import hashlib
import importlib.metadata
import io
import json
import os
import sys
import threading
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

WEIGHTS = os.environ.get("WEIGHTS", "llamaindex/OCRia-1")
REVISION = os.environ.get("REVISION", "489f5fa8f63858545368b9aff44256bbea6e46bc")
DETECTOR = "docling-project/docling-layout-heron"
DETECTOR_REVISION = os.environ.get("DETECTOR_REVISION", "8f39ad3c0b4c58e9c2d2c84a38465abf757272d8")

STATE: dict = {}
LOCK = threading.Lock()


def load() -> None:
    """The pinned snapshots, the package from the model's, then the grounder and the detector on the GPU."""
    from huggingface_hub import snapshot_download

    root = snapshot_download(WEIGHTS, revision=REVISION)
    sys.path.insert(0, root)
    import ocria_grounding

    # Note: `load` reads the weights and the processor from the snapshot folder, and the attention heads the
    # package records for OCRia-1. The system prompt is the snapshot's prompt.txt (the one the answers were
    # generated with), given here: `load` looks for it beside the package's resolved path, which in the Hub's
    # cache is the blob store, and would otherwise download it from the repository's main branch.
    raw = (Path(root) / "prompt.txt").read_bytes()
    prompt = raw.decode("utf-8")
    STATE["og"] = ocria_grounding
    STATE["g"] = ocria_grounding.load(root, device=os.environ.get("BOXES_DEVICE", "cuda"),
                                      system_prompt=prompt)
    STATE["det"] = ocria_grounding.load_detector(snapshot_download(DETECTOR, revision=DETECTOR_REVISION))
    STATE["served"] = {"weights": WEIGHTS, "revision": REVISION, "detector": DETECTOR,
                       "detector_revision": DETECTOR_REVISION,
                       "prompt_sha256": hashlib.sha256(raw).hexdigest(),
                       "transformers": importlib.metadata.version("transformers")}


def words(req: dict, size: tuple[int, int]) -> list[dict] | None:
    """The page's text-layer words in pixels of the image (`size`), or the card's `words` as sent."""
    if not req.get("pdf_b64"):
        return req.get("words")
    import pypdfium2 as pdfium

    from ocria_grounding.pdf import page_words

    doc = pdfium.PdfDocument(base64.b64decode(req["pdf_b64"]))
    try:
        got = page_words(doc[0], dpi=req["dpi"])
    finally:
        doc.close()
    sx, sy = size[0] / req["render_size"][0], size[1] / req["render_size"][1]
    return [{**w, "box": [w["box"][0] * sx, w["box"][1] * sy, w["box"][2] * sx, w["box"][3] * sy]}
            for w in got]


def ground(req: dict) -> dict:
    from PIL import Image

    image = Image.open(io.BytesIO(base64.b64decode(req["image_png_b64"]))).convert("RGB")
    page = STATE["og"].ground_layout(STATE["g"], image, req["answer"], detector=STATE["det"],
                                     words=words(req, image.size))
    return {**page, "served": STATE["served"]}


class Handler(BaseHTTPRequestHandler):
    def _send(self, code: int, obj: dict) -> None:
        body = json.dumps(obj).encode()
        self.send_response(code)
        self.send_header("Content-Type", "application/json")
        self.send_header("Content-Length", str(len(body)))
        self.end_headers()
        self.wfile.write(body)

    def do_GET(self) -> None:  # noqa: N802
        if self.path == "/served": return self._send(200, STATE["served"])
        if self.path == "/health": return self._send(200, {"ok": True})
        self._send(404, {"error": "not found"})

    def do_POST(self) -> None:  # noqa: N802
        if self.path != "/ground": return self._send(404, {"error": "not found"})
        try:
            req = json.loads(self.rfile.read(int(self.headers.get("Content-Length", 0))))
            if not isinstance(req.get("answer"), str) or not req.get("image_png_b64"):
                raise ValueError("image_png_b64 and answer are required")
        except Exception as exc:
            return self._send(400, {"error": f"bad request: {exc}"})
        try:
            with LOCK:
                page = ground(req)
        except Exception as exc:
            return self._send(500, {"error": repr(exc)})
        self._send(200, page)

    def log_message(self, fmt, *args) -> None:
        pass


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--host", default="0.0.0.0")
    ap.add_argument("--port", type=int, default=8100)
    a = ap.parse_args()
    load()
    print(f"OCRia-1 layout boxes on http://{a.host}:{a.port}: {STATE['served']}", flush=True)
    ThreadingHTTPServer((a.host, a.port), Handler).serve_forever()


if __name__ == "__main__":
    main()
